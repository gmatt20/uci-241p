import java.util.HashMap;
import java.util.Map;

public class Main {
  public static void prepare(Map<Character, Integer> alphabet, String s1) {
    for (char c = 'a'; c <= 'z'; c++) {
      alphabet.put(c, 0);
    }

    for (char c : s1.toCharArray()) {
      alphabet.merge(c, 1, Integer::sum);
    }
  }

  public static boolean backtrack(Map<Character, Integer> alphabet, int len, String s2, String curr) {
    if (curr.length() == len)
      return s2.contains(curr);

    for (char c = 'a'; c <= 'z'; c++) {
      if (alphabet.get(c) > 0) {
        alphabet.put(c, alphabet.get(c) - 1);
        if (backtrack(alphabet, len, s2, curr + c)) {
          alphabet.put(c, alphabet.get(c) + 1);
          return true;
        }
        alphabet.put(c, alphabet.get(c) + 1);
      }
    }

    return false;
  }

  public static void main() {
    // Test cases generated by ChatGPT.
    String s1 = "ab";
    String s2 = "eidbaooo";
    Map<Character, Integer> alphabet = new HashMap<>(26);
    prepare(alphabet, s1);
    System.out.println(backtrack(alphabet, s1.length(), s2, "")); // true

    s1 = "ab";
    s2 = "eidboaoo";
    prepare(alphabet, s1);
    System.out.println(backtrack(alphabet, s1.length(), s2, "")); // false

    s1 = "adc";
    s2 = "dcda";
    prepare(alphabet, s1);
    System.out.println(backtrack(alphabet, s1.length(), s2, "")); // true

    s1 = "hello";
    s2 = "ooolleoooleh";
    prepare(alphabet, s1);
    System.out.println(backtrack(alphabet, s1.length(), s2, "")); // false

    s1 = "a";
    s2 = "a";
    prepare(alphabet, s1);
    System.out.println(backtrack(alphabet, s1.length(), s2, "")); // true

    s1 = "a";
    s2 = "b";
    prepare(alphabet, s1);
    System.out.println(backtrack(alphabet, s1.length(), s2, "")); // false
  }
}
